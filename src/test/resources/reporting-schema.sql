-- Test-only compatibility for the pre-existing Employee @Table unique(email)
-- declaration, whose email field is absent. Production schema is never altered.
CREATE TABLE IF NOT EXISTS employees (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id VARCHAR(50) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 employee_designation VARCHAR(50) NOT NULL,
 employee_status VARCHAR(50) NOT NULL,
 fund_join_date DATE,
 fund_exit_date DATE,
 created_at TIMESTAMP NOT NULL,
 updated_at TIMESTAMP NOT NULL,
 deactivation_reason VARCHAR(255),
 deactivated_at TIMESTAMP,
 email VARCHAR(255) DEFAULT RANDOM_UUID() UNIQUE
);
